-- ============================================================
-- Audit trail for terms/patterns + admin rollback.
-- Logs changes made through the authenticated API (auth.uid() present);
-- service_role / SQL seed operations are intentionally not logged.
-- ============================================================

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  table_name text not null check (table_name in ('terms', 'patterns')),
  record_id bigint not null,
  action text not null check (action in ('insert', 'update', 'delete')),
  before jsonb,
  after jsonb,
  changed_by uuid,
  changed_by_name text,
  created_at timestamptz not null default now(),
  reverted_at timestamptz,
  reverted_by uuid
);

create index if not exists audit_log_created on public.audit_log (created_at desc);
create index if not exists audit_log_target on public.audit_log (table_name, record_id);

alter table public.audit_log enable row level security;
revoke all on public.audit_log from anon;
grant select on public.audit_log to authenticated;
grant all on public.audit_log to service_role;
grant usage, select on sequence public.audit_log_id_seq to service_role;

drop policy if exists audit_log_select_admin on public.audit_log;
create policy audit_log_select_admin on public.audit_log
  for select to authenticated
  using (public.is_admin());

create or replace function public.log_table_change()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_uid uuid := auth.uid();
  v_name text;
  v_action text;
  v_before jsonb;
  v_after jsonb;
  v_record bigint;
begin
  -- Seed/backup jobs use service_role and have no auth.uid(); don't spam the log.
  if v_uid is null then
    return coalesce(new, old);
  end if;

  if tg_op = 'INSERT' then
    v_action := 'insert';
    v_before := null;
    v_after := to_jsonb(new);
  elsif tg_op = 'DELETE' then
    v_action := 'delete';
    v_before := to_jsonb(old);
    v_after := null;
  else
    if tg_table_name = 'terms' and new.deleted and not old.deleted then
      v_action := 'delete';
    else
      v_action := 'update';
    end if;
    v_before := to_jsonb(old);
    v_after := to_jsonb(new);
  end if;

  v_record := coalesce((v_after->>'id')::bigint, (v_before->>'id')::bigint);
  select username into v_name from public.profiles where id = v_uid;

  insert into public.audit_log
    (table_name, record_id, action, before, after, changed_by, changed_by_name)
  values
    (tg_table_name, v_record, v_action, v_before, v_after, v_uid, v_name);

  return coalesce(new, old);
end;
$$;

drop trigger if exists audit_terms_change on public.terms;
create trigger audit_terms_change
  after insert or update or delete on public.terms
  for each row execute function public.log_table_change();

drop trigger if exists audit_patterns_change on public.patterns;
create trigger audit_patterns_change
  after insert or update or delete on public.patterns
  for each row execute function public.log_table_change();

create or replace function public.rollback_audit(log_id bigint)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  l public.audit_log%rowtype;
  v_cats text[];
begin
  if not public.is_admin() then
    raise exception 'only administrators can rollback changes';
  end if;

  select * into l from public.audit_log where id = log_id for update;
  if not found then
    raise exception 'audit entry % not found', log_id;
  end if;
  if l.reverted_at is not null then
    raise exception 'audit entry % has already been reverted', log_id;
  end if;

  if l.table_name = 'terms' then
    if l.action = 'insert' then
      update public.terms
        set deleted = true, updated_by = auth.uid(), updated_at = now()
        where id = l.record_id;
    else
      v_cats := coalesce(
        array(select jsonb_array_elements_text(l.before -> 'cats')),
        '{}'::text[]
      );
      update public.terms
        set base_id = (l.before->>'base_id')::bigint,
            ja = l.before->>'ja',
            reading = l.before->>'reading',
            zh = l.before->>'zh',
            en = l.before->>'en',
            cats = v_cats,
            note = l.before->>'note',
            etym = l.before->>'etym',
            variant = l.before->>'variant',
            abbr = l.before->>'abbr',
            syn = l.before->>'syn',
            img = l.before->>'img',
            deleted = coalesce((l.before->>'deleted')::boolean, false),
            updated_by = auth.uid(),
            updated_at = now()
        where id = l.record_id;
    end if;
  elsif l.table_name = 'patterns' then
    if l.action = 'insert' then
      delete from public.patterns where id = l.record_id;
    else
      insert into public.patterns (id, ja, zh, sort)
      values (
        l.record_id,
        l.before->>'ja',
        l.before->>'zh',
        coalesce((l.before->>'sort')::int, 0)
      )
      on conflict (id) do update
        set ja = excluded.ja, zh = excluded.zh, sort = excluded.sort;
    end if;
  else
    raise exception 'cannot rollback table %', l.table_name;
  end if;

  update public.audit_log
    set reverted_at = now(), reverted_by = auth.uid()
    where id = log_id;
end;
$$;

grant execute on function public.rollback_audit(bigint) to authenticated;
