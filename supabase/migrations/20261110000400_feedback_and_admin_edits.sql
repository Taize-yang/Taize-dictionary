-- ============================================================
-- 1) Only administrators may edit existing terms / patterns.
--    All authenticated users may still INSERT new terms/patterns.
-- 2) Feedback table: users submit feedback; admins read/delete.
-- ============================================================

drop policy if exists terms_update on public.terms;
create policy terms_update on public.terms
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists patterns_update on public.patterns;
create policy patterns_update on public.patterns
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  username text,
  term_id bigint references public.terms(id) on delete set null,
  term_ja text,
  term_zh text,
  message text not null check (char_length(message) between 1 and 2000),
  status text not null default 'new' check (status in ('new', 'read')),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  read_by uuid references auth.users(id) on delete set null
);

create index if not exists feedback_status_created on public.feedback (status, created_at desc);
create index if not exists feedback_user on public.feedback (user_id);

alter table public.feedback enable row level security;
revoke all on public.feedback from anon;

grant select, insert on public.feedback to authenticated;
grant update, delete on public.feedback to authenticated;
grant usage, select on sequence public.feedback_id_seq to authenticated;

grant all on public.feedback to service_role;
grant usage, select on sequence public.feedback_id_seq to service_role;

drop policy if exists feedback_insert on public.feedback;
drop policy if exists feedback_select on public.feedback;
drop policy if exists feedback_update_admin on public.feedback;
drop policy if exists feedback_delete_admin on public.feedback;

create policy feedback_insert on public.feedback
  for insert to authenticated
  with check (user_id = auth.uid());

create policy feedback_select on public.feedback
  for select to authenticated
  using (user_id = auth.uid() or public.is_admin());

create policy feedback_update_admin on public.feedback
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy feedback_delete_admin on public.feedback
  for delete to authenticated
  using (public.is_admin());
