create extension if not exists pg_trgm;

-- ------------------------------------------------------------
-- 1. profiles: one row per auth user (username + role)
-- ------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (username ~ '^[A-Za-z0-9_-]{2,20}$'),
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

-- ------------------------------------------------------------
-- 2. terms: authoritative dictionary (replaces embedded payload)
-- ------------------------------------------------------------
create table if not exists public.terms (
  id bigint generated by default as identity primary key,
  base_id bigint unique,                 -- original workbook row id; null = user-added
  ja text not null check (ja <> ''),
  reading text,
  zh text,
  en text,
  cats text[] not null default '{}',
  note text,
  etym text,
  variant text,
  abbr text,
  syn text,
  img text,
  deleted boolean not null default false,
  created_by uuid default auth.uid() references auth.users(id),
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists terms_ja_trgm on public.terms using gin (ja gin_trgm_ops);
create index if not exists terms_reading_trgm on public.terms using gin (reading gin_trgm_ops);
create index if not exists terms_zh_trgm on public.terms using gin (zh gin_trgm_ops);
create index if not exists terms_base_id on public.terms (base_id);
create index if not exists terms_active on public.terms (id) where deleted = false;

alter table public.terms enable row level security;

-- ------------------------------------------------------------
-- 3. patterns: business sentence patterns
-- ------------------------------------------------------------
create table if not exists public.patterns (
  id int primary key,
  ja text not null,
  zh text,
  sort int not null default 0
);

alter table public.patterns enable row level security;

-- ------------------------------------------------------------
-- 4. favorites: per-user favorites
-- ------------------------------------------------------------
create table if not exists public.favorites (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  term_id bigint not null references public.terms(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, term_id)
);

alter table public.favorites enable row level security;

-- ------------------------------------------------------------
-- 5. library_versions: admin-only backup/publish history
-- ------------------------------------------------------------
create table if not exists public.library_versions (
  id uuid primary key default gen_random_uuid(),
  label text,
  stats jsonb,
  storage_path text,
  created_by uuid default auth.uid() references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.library_versions enable row level security;

-- ------------------------------------------------------------
-- 6. helpers & trigger
-- ------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security invoker
set search_path = public, auth
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false);
$$;

create or replace function public.touch_term()
returns trigger
language plpgsql
security invoker
set search_path = public, auth
as $$
begin
  new.updated_at = now();
  new.updated_by = auth.uid();
  return new;
end;
$$;

drop trigger if exists terms_touch on public.terms;
create trigger terms_touch
before update on public.terms
for each row execute function public.touch_term();

-- ------------------------------------------------------------
-- 7. privileges: anon gets nothing; authenticated gets RLS-gated access
-- ------------------------------------------------------------
revoke all on public.profiles from anon;
revoke all on public.terms from anon;
revoke all on public.patterns from anon;
revoke all on public.favorites from anon;
revoke all on public.library_versions from anon;

grant select on public.profiles to authenticated;
grant select, insert, update on public.terms to authenticated;
grant select on public.patterns to authenticated;
grant select, insert, update, delete on public.favorites to authenticated;
grant select on public.library_versions to authenticated;
grant execute on function public.is_admin() to authenticated;

-- ------------------------------------------------------------
-- 8. RLS policies
-- ------------------------------------------------------------

-- profiles: own row; admin can read all. Writes only via service_role / Edge Function.
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.is_admin());

-- terms: any logged-in user can read and CRUD (soft delete via update)
drop policy if exists terms_select on public.terms;
create policy terms_select on public.terms
  for select to authenticated using (true);

drop policy if exists terms_insert on public.terms;
create policy terms_insert on public.terms
  for insert to authenticated with check (auth.uid() is not null);

drop policy if exists terms_update on public.terms;
create policy terms_update on public.terms
  for update to authenticated
  using (auth.uid() is not null)
  with check (auth.uid() is not null);

-- patterns: read for all logged-in users; writes only admin
drop policy if exists patterns_select on public.patterns;
create policy patterns_select on public.patterns
  for select to authenticated using (true);

drop policy if exists patterns_admin_write on public.patterns;
create policy patterns_admin_write on public.patterns
  for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- favorites: own rows only
drop policy if exists favorites_own on public.favorites;
create policy favorites_own on public.favorites
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- library_versions: admin read; writes via service_role
drop policy if exists library_versions_admin_select on public.library_versions;
create policy library_versions_admin_select on public.library_versions
  for select to authenticated using (public.is_admin());
